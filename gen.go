func main() {
	var symbols []string           // first-seen order keeps the output stable
	names := map[string][]string{} // symbol → fyne icon names using it
	for _, m := range mapping {
		if names[m[1]] == nil {
			symbols = append(symbols, m[1])
		}
		names[m[1]] = append(names[m[1]], "theme.IconName"+m[0])
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by gen.go; DO NOT EDIT.

package mdi3

import (
	_ "embed"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/theme"
)

`)
	for _, s := range symbols {
		fetch(s)
		fmt.Fprintf(&b, "//go:embed icons/%s.svg\nvar svg%s []byte\n\n", s, ident(s))
	}
	b.WriteString(`// Icon returns Material Symbols Outlined (Apache 2.0; wght 400, GRAD 0,
// opsz 24) tinted with the foreground color, or Fyne's icon where Symbols
// has no equivalent.
func (*m3) Icon(n fyne.ThemeIconName) fyne.Resource {
	switch n {
`)
	for _, s := range symbols {
		fmt.Fprintf(&b, "case %s:\nreturn res(%q, svg%s)\n", strings.Join(names[s], ", "), "m3_"+s+".svg", ident(s))
	}
	b.WriteString(`}
	return theme.DefaultTheme().Icon(n)
}

func res(name string, content []byte) fyne.Resource {
	return theme.NewThemedResource(&fyne.StaticResource{StaticName: name, StaticContent: content})
}
`)

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icons.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("icons.go: %d symbols for %d fyne icons\n", len(symbols), len(mapping))
}

// ident turns "check_box.fill1" into "CheckBoxFill1".
func ident(s string) string {
	var out string
	for _, p := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '.' }) {
		out += strings.ToUpper(p[:1]) + p[1:]
	}
	return out
}

func fetch(symbol string) {
	path := "icons/" + symbol + ".svg"
	if _, err := os.Stat(path); err == nil {
		return
	}
	name, variant, ok := strings.Cut(symbol, ".")
	if !ok {
		variant = "default"
	}
	resp, err := http.Get("https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/" + name + "/" + variant + "/24px.svg")
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(resp.Body)
	if err != nil || resp.StatusCode != http.StatusOK || !bytes.HasPrefix(body, []byte("<svg")) {
		log.Fatalf("fetch %s: status %d, err %v", symbol, resp.StatusCode, err)
	}
	if err := os.WriteFile(path, body, 0o644); err != nil {
		log.Fatal(err)
	}
}
